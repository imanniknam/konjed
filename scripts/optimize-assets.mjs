// Asset optimiser: AVIF ladders for big plates, WebP twins for PNG sprites, tiny blur-up placeholders.
// Idempotent: safe to re-run. usage: node scripts/optimize-assets.mjs
import sharp from "sharp";
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";

const ROOT = "public/assets/konjed";
const PLATES = [
  "world/hero-world", "arcade/arcade-hall", "school/school-castle", "showcase/showcase-gallery-night",
  "world/final-sunset-world", "world/castle-sky-world", "school/school-interior", "school/school-people",
];
const WIDTHS = [640, 960, 1280, 1536, 1920, 2560];
const Q = { "world/hero-world": 44 }; // the busiest plate gets a leaner quality
const kb = async (f) => Math.round((await stat(f)).size / 1024);
const lqip = {};
let saved = 0;

// 1) plates → AVIF ladder (+ LQIP)
for (const base of PLATES) {
  const src = `${ROOT}/${base}.webp`;
  const meta = await sharp(src).metadata();
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (!widths.includes(meta.width) && meta.width < 2560) widths.push(meta.width);
  for (const w of widths) {
    const out = `${ROOT}/${base}-${w}.avif`;
    await sharp(src).resize({ width: w, withoutEnlargement: true }).avif({ quality: Q[base] ?? 50, effort: 5, chromaSubsampling: "4:2:0" }).toFile(out);
    console.log(`avif  ${base}-${w}.avif  ${await kb(out)}KB`);
  }
  const tiny = await sharp(src).resize({ width: 24 }).blur(0.6).webp({ quality: 45 }).toBuffer();
  lqip[`/assets/konjed/${base}.webp`] = `data:image/webp;base64,${tiny.toString("base64")}`;
}

// 2) PNG sprites → WebP twins (served via Accept-negotiated rewrite, so every existing .png reference benefits)
async function* walk(dir) { for (const e of await readdir(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); if (e.isDirectory()) yield* walk(p); else yield p; } }
for await (const f of walk(ROOT)) {
  if (!f.endsWith(".png")) continue;
  const out = f.replace(/\.png$/, ".webp");
  await sharp(f).webp({ quality: 80, alphaQuality: 92, effort: 6 }).toFile(out);
  const a = await kb(f), b = await kb(out); saved += a - b;
  console.log(`webp  ${f.replace(ROOT + "/", "")}  ${a}KB → ${b}KB`);
}

// 3) cloud banks: 1200w + a 640w twin; game covers capped at 560w (in place, only when larger)
for (const n of ["a", "b", "c"]) {
  const f = `${ROOT}/world/cloudbank-${n}.webp`;
  const buf = await readFile(f); const m = await sharp(buf).metadata();
  await sharp(buf).resize({ width: 640 }).webp({ quality: 72, alphaQuality: 85, effort: 6 }).toFile(f.replace(".webp", "-640.webp"));
  if (m.width > 1200) await sharp(buf).resize({ width: 1200 }).webp({ quality: 72, alphaQuality: 85, effort: 6 }).toFile(f);
  console.log(`cloud ${n}  ${await kb(f)}KB / 640:${await kb(f.replace(".webp", "-640.webp"))}KB`);
}
for (const n of ["a", "b", "c"]) {
  const f = `${ROOT}/world/cloudbank-${n}.webp`;
  for (const w of [640, 1200]) { const o = `${ROOT}/world/cloudbank-${n}-${w}.avif`; await sharp(f).resize({ width: w, withoutEnlargement: true }).avif({ quality: 55, effort: 5 }).toFile(o); console.log(`cloud avif ${n}-${w} ${await kb(o)}KB`); }
}
{ // the journey "map" art is shown ~170px wide: cap its WebP twin at 480w (the PNG stays as the no-WebP fallback)
  const f = `${ROOT}/school/mission-map.png`; await sharp(f).resize({ width: 480 }).webp({ quality: 80, alphaQuality: 92, effort: 6 }).toFile(f.replace(".png", ".webp")); console.log(`map ${await kb(f.replace(".png", ".webp"))}KB`);
}
for await (const f of walk(`${ROOT}/arcade`)) {
  if (!/game-.*\.webp$/.test(f)) continue;
  const buf = await readFile(f); const m = await sharp(buf).metadata();
  if (m.width > 560) { await sharp(buf).resize({ width: 560 }).webp({ quality: 72, effort: 6 }).toFile(f); console.log(`cover ${path.basename(f)} → ${await kb(f)}KB`); }
}

await writeFile("lib/konjed/lqip.ts", `// generated by scripts/optimize-assets.mjs — tiny blur-up placeholders for the big plates\nexport const LQIP: Record<string, string> = ${JSON.stringify(lqip, null, 2)};\n`);
console.log(`\nPNG→WebP saved ${saved}KB`);
